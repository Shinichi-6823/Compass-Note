/* ============================================================================
 * extract.js ― 打合せメモ（音声入力で書いた文）から、45欄の候補を拾う
 *
 *   画面も localStorage も知りません（Node だけで検査できます）。
 *   寸法の読み取りは コンパスの loadsize.js（LOADSIZE）をそのまま使います ― 読み方を2つ持たないため。
 *
 *   ★守っている決めごと（コンパス loadsize.js と同じ）
 *     1. 当てずっぽうをしない … 手がかりの語が無ければ拾わない。読めない日付は返さない
 *     2. 黙って入れ替えない … ここは候補を返すだけ。欄に入れるのは画面（「使う」を押したとき）
 *     3. 候補が2つあれば両方返す … 選ぶのは人
 *     4. 全文は画面が残す … 抽出は要約ではない
 *
 *   ★手がかりは「同じ文の中」で探します。
 *     例「東京DCの件です。倉庫機能はDCです。」… 1文目の DC は拾わず、2文目だけ拾う。
 *     文で切らないと、物件名の「○○DC」を倉庫機能だと取り違えます（実際に踏みました）。
 * ========================================================================== */
(function (root) {
  'use strict';

  var LS = function () { return root.LOADSIZE || null; };
  var str = function (v) { return String(v == null ? '' : v); };

  /** 文に切る。「。」改行・「・」の箇条書きで切る（「、」では切らない＝細かすぎる） */
  function 文に切る(text) {
    return str(text)
      .replace(/\r/g, function () { return ''; })
      .split(/[。\n]+|(?=^\s*[・※]\s*)/m)
      .map(function (s) { return s.trim(); })
      .filter(Boolean);
  }

  /** 全角の数字・英字を半角に。桁区切りの「,」を外す */
  function ならす(s) {
    var t = str(s).replace(/[！-～]/g, function (c) { return String.fromCharCode(c.charCodeAt(0) - 0xFEE0); });
    return t.replace(/(\d),(?=\d{3}\b)/g, function (m, d) { return d; });
  }

  //  チェックの欄（現在の課題）。★「その他」は普通の言葉なので自動では拾わない
  var 課題 = ['人員不足', '物量増加', '保管スペース不足', '作業効率', '品質向上', '安全性', 'コスト'];
  //  「保管スペース不足」は「スペース不足」とも言うので、言い換えを持つ
  var 課題言換 = {
    '人員不足': ['人員不足', '人手不足', '人が足りな', '人員が足りな'],
    '物量増加': ['物量増加', '物量が増え', '物量の増加', '出荷が増え', '荷物が増え'],
    '保管スペース不足': ['保管スペース不足', 'スペース不足', '置き場が足りな', '保管場所が足りな', '手狭'],
    '作業効率': ['作業効率', '効率が悪', '生産性'],
    '品質向上': ['品質向上', '品質', '誤出荷', '誤配'],
    '安全性': ['安全性', '安全', '労災', 'ケガ'],
    'コスト': ['コスト', '費用', '経費']
  };

  //  選択肢の欄 … [欄id, 手がかりの語（同じ文に要る）, [[選択肢, 言い換え…], …]]
  var 選ぶ表 = [
    ['倉庫機能', /倉庫|機能/, [
      ['TC', /(?:^|[\s、。：:はがをにでものとだ])TC(?![A-Za-z0-9])/],
      ['DC', /(?:^|[\s、。：:はがをにでものとだ])DC(?![A-Za-z0-9])/],
      ['工場内倉庫', /工場内/]]],
    ['新築既設', /新築|既設|既存|建屋/, [['新築', /新築/], ['既設', /既設|既存の建屋|今の建屋/]]],
    ['提案範囲', /提案|範囲|改善/, [['全体改善', /全体(?:改善|で|的)/], ['部分改善', /部分(?:改善|的|だけ)/]]],
    ['コンペ有無', /コンペ|相見積|合い見積/, [['あり', /あり|ある|です|実施/], ['なし', /なし|ない|単独/], ['不明', /不明|分からな|わからな/]]],
    ['図面要否', /図面/, [['不要', /(?:図面[^。]{0,8})?不要|要らな|いらな/], ['詳細', /詳細/], ['概略', /概略|ラフ|ざっくり/]]],
    ['提案書要否', /提案書/, [['不要', /不要|要らな|いらな/], ['要', /要|欲し|ほし|出し|提出|必要/]]],
    ['建屋図面', /図面|CAD|DXF|PDF/i, [
      ['あり（CAD）', /CAD|ＣＡＤ|DXF|DWG/i],
      ['あり（PDF）', /PDF|ＰＤＦ/i],
      ['なし', /図面(?:は)?(?:な|無)い|もらえ(?:な|ませ)/]]],
  ];

  //  数＋単位の欄 … [欄id, 手がかり（同じ文）, 数を取る正規表現, 後ろに付ける単位]
  var 数表 = [
    ['要求能力', /希望|要求|目標|将来|ピーク|能力/, /(?:1日|一日|日)?\s*([0-9]+(?:\.[0-9]+)?)\s*(?:行|ライン)/, '行'],
    ['作業量', /作業量|オーダー数|行数|いま|現在|今/, /([0-9]+(?:\.[0-9]+)?)\s*(オーダー|行)/, ''],
    ['SKU数', /SKU|ＳＫＵ|品番|アイテム数|ロケーション/i, /([0-9]+(?:\.[0-9]+)?)\s*(?:点|品番|アイテム|SKU|ロケーション)?/i, ''],
    ['人員数', /人員|作業者|スタッフ|現場|庫内|体制/, /([0-9]+)\s*(?:名|人)/, '名'],
    ['入荷量', /入荷|入庫/, /([0-9]+(?:\.[0-9]+)?)\s*(パレット|ケース|個|行|オーダー|台|t|トン)/i, ''],
    ['出荷量', /出荷|出庫/, /([0-9]+(?:\.[0-9]+)?)\s*(パレット|ケース|個|行|オーダー|台|t|トン)/i, ''],
    ['在庫量', /在庫|保管/, /([0-9]+(?:\.[0-9]+)?)\s*(パレット|ケース|個|ロケーション|間口|t|トン)/i, ''],
    ['予算規模', /予算/, /([0-9]+(?:\.[0-9]+)?)\s*(億|千万|万|千)?円?/, ''],
  ];

  //  自由記述の欄 … [欄id, 手がかり（その文を丸ごと候補にする）]
  var 文表 = [
    ['導入検討背景', /背景|きっかけ|理由|検討(?:し|する|に至)|なぜ/],
    ['ボトルネック', /ボトルネック|いちばん困|一番困|困って|ネックは|いちばんの課題|一番の課題/],
    ['建屋特記', /冷蔵|冷凍|定温|吹き抜け|平屋|床(?:荷重|レベル|強度)|天井高|梁下|柱(?:間|スパン)/],
    ['将来物量', /将来|[0-9]+年後|今後.*増|倍に|伸び/],
    //  ★「作業は8時から17時」を作業内容にしない（それは作業時間。同じ文から2つ拾っていました）
    ['作業内容', /作業(?:内容|の流れ|の中身)|ピッキング|検品|梱包|仕分け|流れは/],
    ['商材特長', /特長|特徴|割れ|こわれ|壊れ|重量物|軽量|温度/],
    ['繁忙期', /繁忙|閑散|ピークは|[0-9]+月が(?:忙|多)/],
    ['物件備考', /温度感|所感|前向き|乗り気|急いで|社内(?:の)?(?:調整|承認)/],
  ];

  /** 「2027年4月」「来年の4月」→ YYYY-MM-DD。読めなければ null（★当てずっぽうをしない） */
  function 日付(文, 基準) {
    var t = ならす(文);
    var now = 基準 ? new Date(基準) : new Date();
    var m = /([0-9]{4})\s*年\s*([0-9]{1,2})\s*月(?:\s*([0-9]{1,2})\s*日)?/.exec(t);
    if (m) return iso(+m[1], +m[2], m[3] ? +m[3] : 1);
    m = /(来年|再来年|今年)\s*(?:の)?\s*([0-9]{1,2})\s*月/.exec(t);
    if (m) return iso(now.getFullYear() + (m[1] === '来年' ? 1 : m[1] === '再来年' ? 2 : 0), +m[2], 1);
    m = /(今月|来月|再来月)/.exec(t);
    if (m) {
      var d = new Date(now.getFullYear(), now.getMonth() + (m[1] === '来月' ? 1 : m[1] === '再来月' ? 2 : 0), 1);
      return iso(d.getFullYear(), d.getMonth() + 1, 1);
    }
    return null;                      // 「春ごろ」「年度内」などは返さない
  }
  function iso(y, mo, d) {
    if (!(mo >= 1 && mo <= 12) || !(d >= 1 && d <= 31)) return null;
    var p = function (n) { return ('0' + n).slice(-2); };
    return y + '-' + p(mo) + '-' + p(d);
  }

  /** 「8時から17時」→ 08:00-17:00。読めなければ null */
  function 時間帯(文) {
    var t = ならす(文);
    var m = /([0-9]{1,2})\s*(?:時|:)\s*([0-9]{1,2})?\s*(?:分)?\s*(?:から|〜|～|~|-|ー)\s*([0-9]{1,2})\s*(?:時|:)\s*([0-9]{1,2})?/.exec(t);
    if (!m) return null;
    var h1 = +m[1], h2 = +m[3];
    if (h1 > 24 || h2 > 24) return null;
    var p = function (n) { return ('0' + (n || 0)).slice(-2); };
    return p(h1) + ':' + p(m[2]) + '-' + p(h2) + ':' + p(m[4]);
  }

  /**
   * メモから候補を拾う。
   * @param {string} text 打合せメモの全文
   * @param {{今日?:string}} [opt] 検査で日付を固定するため
   * @returns {Array<{id:string, value:*, 元:string}>} 拾えなければ []
   */
  function 拾う(text, opt) {
    opt = opt || {};
    var 文s = 文に切る(text);
    if (!文s.length) return [];
    var 全文 = ならす(str(text));
    var out = [];
    var 済 = {};                                    // 1欄につき最初の1つ（寸法だけは複数返す）
    function 足す(id, value, 元) {
      if (value == null || value === '' || (Array.isArray(value) && !value.length)) return;
      if (済[id]) return;
      済[id] = true;
      out.push({ id: id, value: value, 元: str(元).trim() });
    }

    // ── ① 現在の課題（チェック。全文から探す。言い換えも見る） ──
    var 当たり = [], 元課題 = [];
    課題.forEach(function (k) {
      var hit = (課題言換[k] || [k]).find(function (w) { return 全文.indexOf(w) >= 0; });
      if (hit) { 当たり.push(k); 元課題.push(hit); }
    });
    if (当たり.length) 足す('現状課題', 当たり, 元課題.join('／'));

    // ── ② 収納・搬送物サイズ（コンパスの読み手。★複数ぜんぶ返す） ──
    var ls = LS();
    if (ls) {
      ls.parseSize(全文).forEach(function (s) {
        out.push({ id: '収納サイズ', value: s.W + '×' + s.D + '×' + s.H, 元: s.元 });
      });
      if (out.some(function (o) { return o.id === '収納サイズ'; })) 済['収納サイズ'] = true;
    }

    // ── ③〜⑦ 文ごとに見る ──
    文s.forEach(function (文) {
      var n = ならす(文);

      // ③ 重量
      var kg = /([0-9]+(?:\.[0-9]+)?)\s*(?:kg|ｋｇ|キロ(?:グラム)?)/i.exec(n);
      if (kg && /重|重さ|重量|ケース|パレット|オリコン|箱/.test(n)) 足す('収納重量', kg[1], kg[0]);

      // ④ 選択肢の欄（★手がかりが同じ文に無ければ拾わない）
      選ぶ表.forEach(function (row) {
        var id = row[0], 手がかり = row[1], 候補 = row[2];
        if (!手がかり.test(n)) return;
        for (var i = 0; i < 候補.length; i++) {
          if (候補[i][1].test(n)) { 足す(id, 候補[i][0], 文); return; }
        }
      });

      // ⑤ 数＋単位
      数表.forEach(function (row) {
        var id = row[0], 手がかり = row[1], re = row[2], 単位 = row[3];
        if (!手がかり.test(n)) return;
        var m = re.exec(n);
        if (!m || !m[1]) return;
        var v = m[1] + (m[2] ? m[2] : '') + 単位;
        if (id === '予算規模') {
          var 倍 = { '億': 100000, '千万': 10000, '万': 10, '千': 1 }[m[2]];
          if (!倍) return;                           // 単位が無い数は予算と決めつけない
          v = String(Math.round(parseFloat(m[1]) * 倍));   // 千円
        }
        足す(id, v, m[0]);
      });

      // ⑥ 時間帯
      var hm = 時間帯(n);
      if (hm) {
        if (/入荷|入庫|着荷/.test(n)) 足す('入荷時間', hm, 文);
        else if (/出荷|出庫|トラック|〆|締め/.test(n)) 足す('出荷時間', hm, 文);
        else if (/作業|稼働|営業|シフト/.test(n)) 足す('作業時間', hm, 文);
      }

      // ⑦ 日付（手がかりのある文だけ）
      if (/稼働|立ち上げ|立上げ|開始/.test(n)) 足す('稼働予定', 日付(n, opt.今日), 文);
      if (/受注|発注|内示|決定/.test(n)) 足す('受注時期', 日付(n, opt.今日), 文);

      // ⑧ 自由記述（その文を丸ごと）
      文表.forEach(function (row) {
        if (row[1].test(n)) 足す(row[0], 文, 文);
      });
    });

    return out;
  }

  /**
   * アクション（次の一手）を拾う。
   * @returns {Array<{action:string, when:string, 元:string}>}
   */
  function アクション(text, opt) {
    opt = opt || {};
    //  ★「打合せ」「訪問」だけでは拾わない … 打合せの報告そのものが混ざるため
    //    （「架空商事の東京DCで打合せ」を次の一手として拾ってしまい、実際に外しました）
    //    これから やること を表す語（次回・までに・送る・予定…）が要る
    var これから = /次回|次は|までに|まで に|送る|送付|提出|出す|提示|回答|手配|依頼|確認する|用意/;
    var 先の予定 = /(?:訪問|打合せ|打ち合わせ|現調|現地調査|見積|提案|図面)[^。]{0,10}(?:予定|する|します|したい|お願い|いただく|もらう)/;
    return 文に切る(text).filter(function (文) {
      var n = ならす(文);
      return これから.test(n) || 先の予定.test(n);
    }).map(function (文) {
      return { action: 文, when: 日付(文, opt.今日) || '', 元: 文 };
    });
  }

  var API = { 拾う: 拾う, アクション: アクション, 文に切る: 文に切る, 日付: 日付, 時間帯: 時間帯, ならす: ならす, 課題: 課題 };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  root.EXTRACT = API;
})(typeof self !== 'undefined' ? self : this);
